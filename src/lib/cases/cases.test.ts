test('One theme system: light and dark token sets match, and mounted pages use tokens, not hardcoded colours', () => {
  const css = readFileSync('src/index.css', 'utf8');
  const block = (start: string) => {
    const i = css.indexOf(start);
    return new Set([...css.slice(i, css.indexOf('}', i)).matchAll(/(--[a-z0-9-]+):/g)].map((m) => m[1]));
  };
  const light = block(':root {');
  const darkOs = block(':root:not([data-theme="light"])');
  const darkSet = block(':root[data-theme="dark"]');
  light.delete('--shadow');
  for (const k of light) {
    assert.ok(darkOs.has(k), 'OS dark misses ' + k);
    assert.ok(darkSet.has(k), 'explicit dark misses ' + k);
  }
  const html = readFileSync('index.html', 'utf8');
  assert.match(html, /localStorage\.getItem\('pitt-theme'\)/); // set before first paint: no flash of the wrong theme
  for (const f of MOUNTED) {
    const t = readFileSync(f, 'utf8');
    assert.doesNotMatch(t, /#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b(?!\w)|bg-slate|text-white|from-indigo|to-violet|colorScheme|ROOM_THEME/, f);
    assert.doesNotMatch(t, /angle=\{?-?\d/, f); // no angled chart labels
  }
});

