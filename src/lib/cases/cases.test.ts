test('USD conversion: day rate, no double conversion, unknown currency and missing rate are unavailable', () => {
  const r = eurPerUsd('2026-10-20')!;
  assert.ok(Math.abs(r - 0.89048968856129396) < 1e-12);
  const u = toUsd(100, 'EUR', '2026-10-20 11:44');
  assert.ok(u.kind === 'usd' && Math.abs(u.usd - 100 / r) < 1e-9);
  const same = toUsd(100, 'USD', '2026-10-20');
  assert.ok(same.kind === 'usd' && same.usd === 100);
  assert.equal(toUsd(100, 'unknown', '2026-10-20').kind, 'unavailable');
  assert.equal(toUsd(100, 'EUR', '2025-01-01').kind, 'unavailable');
  assert.equal(toUsd(100, 'EUR', null).kind, 'unavailable');
  assert.match(usdInText('€34,785/week', '2026-10-20'), /^≈ \$[\d,]+\/week$/);
  assert.equal(usdInText('€5', '1999-01-01'), '[amount in source currency]');
});

test('Convert before aggregation: daily EUR at each day rate, then summed (not the sum at one rate)', () => {
  const days = [{ day: '2026-10-14', eur: 1000 }, { day: '2026-10-20', eur: 1000 }];
  const s = sumDailyEurToUsd(days);
  assert.ok(s.kind === 'usd');
  assert.ok(Math.abs(s.usd - (1000 / RATES['2026-10-14'] + 1000 / RATES['2026-10-20'])) < 1e-9);
  assert.ok(Math.abs(s.usd - 2000 / RATES['2026-10-20']) > 1e-6);
  assert.equal(sumDailyEurToUsd([...days, { day: '1999-01-01', eur: 1 }]).kind, 'unavailable'); // no partial sums
});

