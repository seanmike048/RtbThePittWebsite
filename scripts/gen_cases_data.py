#!/usr/bin/env python3
"""
Builds the case-layer data files from two stored sources, so no component carries case content:

  scripts/run-2026-10-21-1655.json        The Pitt run of 21 Oct 2026, 4:55 PM (#thepittoutput), fields copied verbatim
  data/snowflake/amazon-spend-2026-10-21.json   Read-only Snowflake snapshot: alert view, daily Amazon spend, FX table

Writes:
  fixtures/thepitt-run-2026-10-21-1655.txt  Paste fixture: the run headline and the three Jira drafts, verbatim
  src/lib/cases/fixture.data.ts            The same text, plus the digest-only fields (meta, findings) per case ID
  src/lib/cases/spend.data.ts              The Snowflake snapshot as typed constants

The original Slack paste (pasted-text-1_2026-10-22_05-05-34.txt) is not in the repository. The fixture is assembled
only from verbatim fields of the stored run, never rewritten; replace it with the original paste when available.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
run = json.loads((ROOT / 'scripts/run-2026-10-21-1655.json').read_text())
snap = json.loads((ROOT / 'data/snowflake/amazon-spend-2026-10-21.json').read_text())

order = ['5412', '5449', '4883']
text = run['headline'] + '\n\n' + '\n\n'.join(run['cases'][k]['draft'] for k in order) + '\n'
(ROOT / 'fixtures').mkdir(exist_ok=True)
(ROOT / 'fixtures/thepitt-run-2026-10-21-1655.txt').write_text(text)

digest = {
    'LIVE-%s-amazon_dsp' % k: {'meta': run['cases'][k]['meta'], 'findings': run['cases'][k]['findings']}
    for k in order
}
js = lambda o: json.dumps(o, ensure_ascii=False, indent=2)
(ROOT / 'src/lib/cases/fixture.data.ts').write_text(
    '// Generated by scripts/gen_cases_data.py. Do not edit by hand.\n'
    '/** Paste fixture: the 21 Oct 2026 4:55 PM run headline and its three Jira drafts, verbatim from the stored run. */\n'
    'export const RUN_FIXTURE_TEXT = ' + js(text) + ';\n\n'
    '/** Where the fixture comes from. */\n'
    'export const RUN_FIXTURE_SOURCE = ' + js(run['source'] + ' Assembled from the stored fields (headline + drafts); the original Slack paste is not in the repository.') + ';\n\n'
    '/** Digest-only fields of the same run (not in the drafts), keyed by case ID. */\n'
    'export const RUN_DIGEST: Record<string, { meta: string; findings: string[] }> = ' + js(digest) + ';\n'
)

(ROOT / 'src/lib/cases/spend.data.ts').write_text(
    '// Generated by scripts/gen_cases_data.py from data/snowflake/amazon-spend-2026-10-21.json. Do not edit by hand.\n'
    "import type { SpendSnapshot } from './types.ts';\n\n"
    'export const SPEND_SNAPSHOT: SpendSnapshot = ' + js(snap) + ';\n'
)
print('wrote fixture (%d chars), fixture.data.ts, spend.data.ts (%d daily rows)' % (len(text), len(snap['daily'])))
